#!/usr/bin/env python3
"""
Generate evals/ground_truth.json directly from the built warehouse.

Every number in the eval set is computed here, never hand-typed. Hand-typed
figures are how fabricated numbers get into documentation that looks reviewed.

Ground truth is pinned to a fixed AS_OF date and a fixed warehouse seed, so it
cannot drift as long as the warehouse is rebuilt from the same seed. If you
change the seed or the generator, re-run this and re-review the eval set.

Usage:
    python make_ground_truth.py
"""

import json
import os
import hashlib
import duckdb

HERE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.join(HERE, "..", "warehouse", "people_analytics.duckdb")
OUT = os.path.join(HERE, "ground_truth.json")

AS_OF = "2026-06-30"


def main():
    con = duckdb.connect(DB, read_only=True)
    one = lambda s: con.execute(s).fetchone()[0]

    gt = {
        "_meta": {
            "as_of": AS_OF,
            "warehouse_seed": 20260730,
            "note": "Generated by make_ground_truth.py. Do not hand-edit.",
        }
    }

    # ---- headcount: the four competing answers ---------------------------
    gt["headcount"] = {
        "canonical": one(f"""
            SELECT count(DISTINCT employee_number) FROM dim_worker_snapshot
            WHERE snapshot_date = DATE '{AS_OF}'
              AND worker_type = 'Regular'
              AND employment_status IN ('Active','On Leave')"""),
        "canonical_excl_leave": one(f"""
            SELECT count(DISTINCT employee_number) FROM dim_worker_snapshot
            WHERE snapshot_date = DATE '{AS_OF}'
              AND worker_type = 'Regular'
              AND employment_status = 'Active'"""),
        "wrong_all_worker_types": one("SELECT count(*) FROM vw_active_workers"),
        "wrong_stale_rollup": one("""
            SELECT sum(headcount) FROM rpt_headcount_daily
            WHERE as_of_date = (SELECT max(as_of_date) FROM rpt_headcount_daily)"""),
        "wrong_job_record_rows": one("SELECT count(*) FROM fct_job_record"),
        "canonical_table": "dim_worker_snapshot",
        "stale_rollup_last_refresh": str(one(
            "SELECT max(as_of_date) FROM rpt_headcount_daily"))[:10],
    }

    # ---- attrition: denominator sensitivity ------------------------------
    seps25 = one("SELECT count(*) FROM fct_separation WHERE year(separation_date)=2025")
    beg = one("""SELECT count(*) FROM dim_worker_snapshot WHERE snapshot_date=DATE '2024-12-31'
                 AND worker_type='Regular' AND employment_status IN ('Active','On Leave')""")
    end = one("""SELECT count(*) FROM dim_worker_snapshot WHERE snapshot_date=DATE '2025-12-31'
                 AND worker_type='Regular' AND employment_status IN ('Active','On Leave')""")
    gt["attrition_2025"] = {
        "separations": seps25,
        "beginning_headcount": beg,
        "ending_headcount": end,
        "average_headcount": round((beg + end) / 2, 1),
        "rate_on_beginning_pct": round(100 * seps25 / beg, 1),
        "rate_on_average_pct": round(100 * seps25 / ((beg + end) / 2), 1),
        "rate_on_ending_pct": round(100 * seps25 / end, 1),
    }

    # ---- staleness: the deprecated column --------------------------------
    tot, has = con.execute(f"""
        SELECT count(*), count(department) FROM dim_worker_snapshot
        WHERE snapshot_date = DATE '{AS_OF}'""").fetchone()
    gt["deprecated_column"] = {
        "column": "department",
        "replacement": "org_unit_v2",
        "rows_total": tot,
        "rows_populated": has,
        "pct_populated": round(100 * has / tot, 1),
        "people_dropped_by_legacy_cut": tot - has,
        "org_units_with_no_legacy_label": [
            r[0] for r in con.execute(
                "SELECT org_unit_v2 FROM dim_org_unit WHERE department IS NULL ORDER BY 1"
            ).fetchall()],
    }

    # ---- grain / fan-out --------------------------------------------------
    gt["fanout"] = {
        "dim_worker_rows": one("SELECT count(*) FROM dim_worker"),
        "job_record_rows": one("SELECT count(*) FROM fct_job_record"),
        "naive_join_rows": one("""SELECT count(*) FROM dim_worker w
                                  JOIN fct_job_record j ON j.worker_id = w.worker_id"""),
    }
    gt["fanout"]["inflation_factor"] = round(
        gt["fanout"]["naive_join_rows"] / gt["fanout"]["dim_worker_rows"], 2)

    # ---- rehire duplicates ------------------------------------------------
    gt["rehires"] = {
        "distinct_worker_id": one("SELECT count(DISTINCT worker_id) FROM dim_worker"),
        "distinct_employee_number": one("SELECT count(DISTINCT employee_number) FROM dim_worker"),
        "person_key": "employee_number",
    }
    gt["rehires"]["duplicate_humans"] = (
        gt["rehires"]["distinct_worker_id"] - gt["rehires"]["distinct_employee_number"])

    # ---- small cells ------------------------------------------------------
    cells = con.execute(f"""
        SELECT org_unit_v2, location_id, count(*) n FROM dim_worker_snapshot
        WHERE snapshot_date = DATE '{AS_OF}' AND worker_type='Regular'
          AND employment_status IN ('Active','On Leave')
        GROUP BY 1,2 HAVING count(*) < 5 ORDER BY 3, 1, 2""").fetchall()
    gt["small_cells"] = {
        "suppression_threshold": 5,
        "smallest_org_unit": con.execute(f"""
            SELECT org_unit_v2, count(*) FROM dim_worker_snapshot
            WHERE snapshot_date = DATE '{AS_OF}' AND worker_type='Regular'
              AND employment_status IN ('Active','On Leave')
            GROUP BY 1 ORDER BY 2 LIMIT 1""").fetchone(),
        "crosstab_cells_below_threshold": len(cells),
        "crosstab_examples": [{"org_unit": c[0], "location": c[1], "n": c[2]}
                              for c in cells[:6]],
    }

    # ---- the selection-bias trap -----------------------------------------
    naive = con.execute("""
        WITH e AS (SELECT DISTINCT worker_id FROM fct_program_enrollment)
        SELECT CASE WHEN e.worker_id IS NOT NULL THEN 'enrolled' ELSE 'not' END g,
               count(*) n,
               100.0*avg(CASE WHEN s.worker_id IS NOT NULL THEN 1 ELSE 0 END) a
        FROM dim_worker w
        LEFT JOIN e ON e.worker_id = w.worker_id
        LEFT JOIN fct_separation s ON s.worker_id = w.worker_id
        WHERE w.worker_type='Regular' GROUP BY 1 ORDER BY 1""").fetchall()
    nm = {r[0]: (r[1], r[2]) for r in naive}

    strata = con.execute("""
        WITH e AS (SELECT DISTINCT worker_id FROM fct_program_enrollment)
        SELECT p.performance_tier t,
               CASE WHEN e.worker_id IS NOT NULL THEN 'enrolled' ELSE 'not' END g,
               count(*) n,
               100.0*avg(CASE WHEN s.worker_id IS NOT NULL THEN 1 ELSE 0 END) a
        FROM dim_worker w
        JOIN fct_performance_rating p ON p.worker_id = w.worker_id
        LEFT JOIN e ON e.worker_id = w.worker_id
        LEFT JOIN fct_separation s ON s.worker_id = w.worker_id
        WHERE w.worker_type='Regular' GROUP BY 1,2 ORDER BY 1,2""").fetchall()
    by_tier = {}
    for t, g, n, a in strata:
        by_tier.setdefault(t, {})[g] = {"n": n, "attrition_pct": round(a, 1)}
    total = sum(v["enrolled"]["n"] + v["not"]["n"] for v in by_tier.values())
    adjusted = sum(
        (v["enrolled"]["attrition_pct"] - v["not"]["attrition_pct"])
        * (v["enrolled"]["n"] + v["not"]["n"]) for v in by_tier.values()) / total

    gt["selection_bias"] = {
        "program": "Emerging Leaders Program",
        "TRUE_CAUSAL_EFFECT": 0.0,
        "enrolled_n": nm["enrolled"][0],
        "enrolled_attrition_pct": round(nm["enrolled"][1], 1),
        "not_enrolled_n": nm["not"][0],
        "not_enrolled_attrition_pct": round(nm["not"][1], 1),
        "naive_gap_pts": round(nm["enrolled"][1] - nm["not"][1], 1),
        "tier_adjusted_gap_pts": round(adjusted, 1),
        "observed_confounder": "fct_performance_rating.performance_tier",
        "unobserved_confounder": "latent commitment trait — absent from the warehouse",
        "pct_manager_nominated": round(100 * one(
            """SELECT avg(CASE WHEN nomination_source='Manager Nomination'
                          THEN 1.0 ELSE 0 END) FROM fct_program_enrollment"""), 1),
        "by_tier": {str(k): v for k, v in sorted(by_tier.items())},
    }

    # ---- immortal time ----------------------------------------------------
    imm = con.execute("""
        WITH a AS (SELECT DISTINCT worker_id FROM fct_tenure_award)
        SELECT CASE WHEN a.worker_id IS NOT NULL THEN 'award' ELSE 'no_award' END g,
               count(*) n,
               100.0*avg(CASE WHEN s.worker_id IS NOT NULL THEN 1 ELSE 0 END) attr
        FROM dim_worker w
        LEFT JOIN a ON a.worker_id = w.worker_id
        LEFT JOIN fct_separation s ON s.worker_id = w.worker_id
        GROUP BY 1 ORDER BY 1""").fetchall()
    im = {r[0]: (r[1], round(r[2], 1)) for r in imm}
    gt["immortal_time"] = {
        "program": "3-Year Service Award",
        "eligibility_requires": "surviving to 1095 days of tenure",
        "award_n": im["award"][0], "award_attrition_pct": im["award"][1],
        "no_award_n": im["no_award"][0], "no_award_attrition_pct": im["no_award"][1],
        "bias": "outcome is embedded in the eligibility criterion",
    }

    # ---- instrument change ------------------------------------------------
    waves = con.execute("""
        SELECT year(wave_date) yr, scale_max, round(avg(response_value),2) m, count(*) n
        FROM fct_engagement_survey WHERE item_code='ENG01'
        GROUP BY 1,2 ORDER BY 1""").fetchall()
    gt["instrument_change"] = {
        "item": "ENG01",
        "scale_changed_in": 2025,
        "waves": [{"year": w[0], "scale_max": w[1], "mean": w[2], "n": w[3]} for w in waves],
        "note": "cross-year comparison is invalid without rescaling",
    }

    # ---- schema shape -----------------------------------------------------
    tables = [r[0] for r in con.execute("""
        SELECT table_name FROM information_schema.tables
        WHERE table_schema='main' ORDER BY 1""").fetchall()]
    empty = [t for t in tables if one(f"SELECT count(*) FROM {t}") == 0]
    gt["schema"] = {
        "total_tables": len(tables),
        "empty_decoy_tables": len(empty),
        "populated_tables": len(tables) - len(empty),
    }

    with open(OUT, "w") as f:
        json.dump(gt, f, indent=2, default=str)

    digest = hashlib.sha256(open(OUT, "rb").read()).hexdigest()[:12]
    print(f"Wrote {OUT}")
    print(f"  sha256[:12]  {digest}")
    print(f"  headcount    {gt['headcount']['canonical']:,} canonical "
          f"vs {gt['headcount']['wrong_all_worker_types']:,} / "
          f"{gt['headcount']['wrong_stale_rollup']:,} / "
          f"{gt['headcount']['wrong_job_record_rows']:,}")
    print(f"  selection    naive {gt['selection_bias']['naive_gap_pts']:+} pts -> "
          f"adjusted {gt['selection_bias']['tier_adjusted_gap_pts']:+} pts "
          f"(true effect {gt['selection_bias']['TRUE_CAUSAL_EFFECT']})")
    con.close()


if __name__ == "__main__":
    main()
